// Clicks through the app at iPhone size and saves screenshots: node tests/flow.js [outdir] [dark]
const path = require('path');
const { chromium } = require(process.env.PLAYWRIGHT || require('path').join(__dirname, '../../travel-tracker/node_modules/playwright'));
(async () => {
  const out = process.argv[2] || '/tmp/mobility-shots';
  const dark = process.argv[3] === 'dark';
  require('fs').mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ channel: 'chrome', args: ['--mute-audio'] });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, colorScheme: dark ? 'dark' : 'light' });
  const p = await ctx.newPage();
  const errors = [];
  p.on('pageerror', (e) => errors.push(e.message));
  p.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
  await p.addInitScript(() => { window.confirm = () => true; window.speechSynthesis.speak = () => {}; });
  await p.goto('file://' + path.resolve(__dirname, '../index.html'));
  const shot = (name, full = false) => p.screenshot({ path: `${out}/${name}.png`, fullPage: full });
  await p.waitForTimeout(300);
  await shot('1-home', true);
  await p.click('[data-act="build"]');
  await p.waitForTimeout(300);
  await shot('2-preview');
  await p.click('[data-act="swap"][data-i="1"]');
  await p.click('[data-act="detail"][data-i="0"]');
  await p.waitForTimeout(800);
  await shot('3-detail');
  await p.click('[data-close]');
  await p.click('[data-act="start"]');
  await p.waitForTimeout(1500);
  await shot('4-player-prep');
  await p.click('[data-act="skip"]');
  await p.waitForTimeout(2200);
  await shot('5-player-hold');
  await shot('5b-player-hold-full', true);
  await p.click('[data-act="pause"]');
  await p.waitForTimeout(300);
  await shot('6-paused');
  await p.click('[data-act="pause"]');
  // Skip through everything to the end.
  for (let i = 0; i < 200 && (await p.$('[data-act="skip"]')); i++) await p.click('[data-act="skip"]');
  await p.waitForTimeout(300);
  await shot('7-done');
  await p.click('[data-act="home"]');
  await p.click('[data-act="library"]');
  await p.waitForTimeout(300);
  await shot('8-library');
  await p.click('[data-act="home"]');
  await p.click('[data-act="settings"]');
  await p.waitForTimeout(300);
  await shot('9-settings', true);
  // Mobility check: answer every test, then results and the home screen with today's session.
  await p.click('[data-act="home"]');
  await p.click('[data-act="check"]');
  await shot('10-check-intro');
  await p.click('[data-act="go"]');
  await p.waitForTimeout(200);
  await shot('11-check-step');
  for (let i = 0; i < 12; i++) await p.click(`[data-act="answer"][data-score="${[0, 1, 2, 1][i % 4]}"]`);
  await p.waitForTimeout(200);
  await shot('12-results', true);
  await p.click('[data-act="use"]');
  await p.click('[data-act="home"]');
  await p.waitForTimeout(200);
  await shot('13-home-after-check');
  await p.click('[data-act="today"]');
  await p.waitForTimeout(500);
  await shot('14-today-session');
  console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no page errors');
  await browser.close();
})();
